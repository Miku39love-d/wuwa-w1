out = os.path.join(HERE, "data", "gap_chat.jsonl")
with open(out, "w", encoding="utf-8") as f:
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")

lens = [len(r["assistant"]) for r in rows]
print(f"生成 {len(rows)} 条 -> {out}")
print(f"assistant 长度: min {min(lens)} / mean {sum(lens)/len(lens):.1f} / max {max(lens)}")
cats = {"天气": 0, "再见": 0, "通识": 0, "金额": 0, "礼貌": 0}
for r in rows:
    u = r["user"]
    if "天气" in u or "雨" in u or "伞" in u or "度" in u or "冷" in u or "热" in u: cats["天气"] += 1
    elif any(k in u for k in ["再见", "拜拜", "先走", "下次聊", "回见", "先这样", "溜了", "晚安", "下线", "告辞"]): cats["再见"] += 1
    elif "选" in u or "哪个多" in u or "哪个大" in u or "哪个钱多" in u: cats["金额"] += 1
    elif "？" in u or "什么" in u or "怎么" in u or "吗" in u or "造" in u or "叫" in u or "岁" in u or "饿" in u or "睡" in u or "忙" in u or "问题" in u or "在吗" in u or "到" in u: cats["通识" if "什么" in u else "礼貌"] += 1
print(cats)
