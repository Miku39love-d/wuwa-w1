rows = []
for item in P:
    if len(item) == 2 and isinstance(item[1], list):
        q, answers = item
    elif len(item) == 2:
        q, a = item
        answers = [a]
    else:
        continue
    for a in answers:
        rows.append({"type": "chat", "user": q, "assistant": a})

# 打乱 + 去重
seen = set()
uniq = []
for r in rows:
    key = (r["user"], r["assistant"])
    if key in seen:
        continue
    seen.add(key)
    uniq.append(r)
random.shuffle(uniq)

out = os.path.join(HERE, "data", "persona_chat.jsonl")
with open(out, "w", encoding="utf-8") as f:
    for r in uniq:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")

# 统计
