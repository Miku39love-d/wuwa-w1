"""补齐对话数据盲区：天气 / 再见 / 通识定义 / 金额选择。
原则（用户明确要求）：
1. 简单对话 = 语义完整、直接对题的短回答，不要残句、不要长文
2. 每个意图多种问法变体，防死记硬背
3. assistant 控制在 8-25 字
输出: data/gap_chat.jsonl
"""
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
random.seed(20261024)

rows = []


def add(user, assistant):
    assert 1 <= len(assistant) <= 30, f"回答超长: {assistant}"
    rows.append({"type": "chat", "user": user, "assistant": assistant})


